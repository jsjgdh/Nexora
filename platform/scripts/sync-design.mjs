#!/usr/bin/env node
/* Syncs the Studio design challenges' judgable half into the execution service.
   The IDE authors challenges (nexora-ide, sibling repo); the platform re-judges
   them for attestation. Only the deterministic structural floor crosses over —
   id, authored revision, checks — never the rubric, reference, alternatives,
   scenarios, hints, or misconceptions: the platform holds what it judges and
   nothing it could teach, leak, or model-score from.
   Run:
     npm run sync:design
   Check (what the verify suite runs):
     npm run sync:design -- --check
   The output is a .ts module rather than .json so it ships inside dist/ with
   the service build — no runtime file copy, no path to misconfigure. Like
   sync-curriculum, the bytes are re-serialized canonical JSON, so a
   CRLF-vs-LF checkout difference can never masquerade as a content change. */

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

const ideSrc = join(root, "..", "..", "nexora-ide", "extensions", "nexora", "curriculum", "design-challenges.json");
const outFile = join(root, "services", "execution", "src", "data", "design-challenges.ts");

/* The seven structural check kinds the platform engine (designAttest.ts) can
   decide. A synced check of any other kind would reach the judge and fall
   through its switch — so the sync refuses to ship it, loudly, here. */
const KNOWN_KINDS = new Set([
  "requires-node",
  "requires-any",
  "requires-edge",
  "requires-path",
  "forbids-edge",
  "requires-prop",
  "no-dangling",
]);

let raw;
try {
  raw = await readFile(ideSrc, "utf8");
} catch {
  throw new Error(
    `cannot sync design challenges: no file at ${ideSrc}\n` +
      `   nexora-ide must be checked out as a sibling of branchcraft (both under the same parent directory).`
  );
}
const doc = JSON.parse(raw);
if (!Array.isArray(doc.challenges) || doc.challenges.length === 0) {
  throw new Error("cannot sync design challenges: the IDE document names no challenges");
}
const entries = doc.challenges.map((c, i) => {
  if (typeof c.id !== "string" || c.id.length === 0) {
    throw new Error(`cannot sync design challenges: challenge ${i} has no id`);
  }
  if (!Number.isInteger(c.version) || c.version < 1) {
    throw new Error(
      `cannot sync design challenges: ${c.id} ships no authored revision — version it in the IDE source first`
    );
  }
  if (!Array.isArray(c.checks) || c.checks.length === 0) {
    throw new Error(`cannot sync design challenges: ${c.id} holds no structural checks`);
  }
  const ids = c.checks.map((k) => k.id);
  if (new Set(ids).size !== ids.length) {
    throw new Error(`cannot sync design challenges: ${c.id} has duplicate check ids`);
  }
  for (const k of c.checks) {
    if (!KNOWN_KINDS.has(k.kind)) {
      throw new Error(
        `cannot sync design challenges: ${c.id} check ${k.id} has kind ${JSON.stringify(k.kind)} the platform engine cannot judge`
      );
    }
  }
  return { id: c.id, version: c.version, checks: c.checks };
});

const emitted =
  `// Generated by npm run sync:design — do not edit by hand.\n` +
  `// Source: nexora-ide/extensions/nexora/curriculum/design-challenges.json\n` +
  `// The structural floor only: id, authored revision, checks. No rubric, no\n` +
  `// reference, no alternatives, no scenarios, no hints, no misconceptions.\n` +
  `export interface SyncedDesignChallenge {\n` +
  `  id: string;\n` +
  `  version: number;\n` +
  `  checks: unknown[];\n` +
  `}\n` +
  `export const SYNCED_DESIGN_CHALLENGES: SyncedDesignChallenge[] = ${JSON.stringify(entries)};\n`;

if (check) {
  let prev = null;
  try {
    prev = await readFile(outFile, "utf8");
  } catch {
    prev = null;
  }
  if (prev !== emitted) {
    throw new Error(
      "design-challenge sync has drifted: the committed registry no longer equals what the IDE source emits — " +
        "run `npm run sync:design` and commit the regenerated module. The platform must never judge stale checks."
    );
  }
  console.log(`design sync clean (${entries.length} challenges).`);
} else {
  await mkdir(dirname(outFile), { recursive: true });
  await writeFile(outFile, emitted, "utf8");
  console.log(`design challenges synced (${entries.map((e) => `${e.id} v${e.version}`).join(", ")}).`);
}
