#!/usr/bin/env node
/* Syncs the debugging labs' answer key into the execution service.
   The IDE authors the labs (nexora-ide, sibling repo); the platform judges them
   for attestation. Only the KEY crosses over — the cause each incident is built
   around, and the cause each candidate fix addresses — and never the symptom,
   the log, the failing tests, the evidence, the hints or the prose of a fix:
   the platform holds what it judges and nothing it could teach. The IDE ships
   the other half, so a learner can read the lab without reading the answer.

   The RUN-mode lab is not synced: it is judged by the learner's own suite
   against their own code, and it has no key to hold.

   Run:
     npm run sync:incidents
   Check (what the verify suite runs):
     npm run sync:incidents -- --check
   The output is a .ts module rather than .json so it ships inside dist/ with
   the service build — no runtime file copy, no path to misconfigure. Like
   sync-curriculum and sync-design, the bytes are re-serialized canonical JSON,
   so a CRLF-vs-LF checkout difference can never masquerade as a content change. */

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

const ideSrc = join(root, "..", "..", "nexora-ide", "extensions", "nexora", "curriculum", "incidents.json");
const outFile = join(root, "services", "execution", "src", "data", "incidents.ts");

let raw;
try {
  raw = await readFile(ideSrc, "utf8");
} catch {
  throw new Error(
    `cannot sync debugging labs: no file at ${ideSrc}\n` +
      `   nexora-ide must be checked out as a sibling of branchcraft (both under the same parent directory).`
  );
}
const doc = JSON.parse(raw);
if (!Array.isArray(doc.incidents) || doc.incidents.length === 0) {
  throw new Error("cannot sync debugging labs: the IDE document names no labs");
}
const version = Number.isInteger(doc.version) && doc.version >= 1 ? doc.version : 1;

const entries = doc.incidents
  .filter((incident) => incident.mode !== "run")
  .map((incident, i) => {
    if (typeof incident.id !== "string" || incident.id.length === 0) {
      throw new Error(`cannot sync debugging labs: lab ${i} has no id`);
    }
    if (typeof incident.rootCause !== "string" || incident.rootCause.trim().length === 0) {
      throw new Error(`cannot sync debugging labs: ${incident.id} declares no root cause — there is no key to judge with`);
    }
    if (!Array.isArray(incident.candidateFixes) || incident.candidateFixes.length < 2) {
      throw new Error(`cannot sync debugging labs: ${incident.id} holds fewer than two candidate fixes`);
    }
    if (!Array.isArray(incident.requiredEvidence) || incident.requiredEvidence.length === 0) {
      throw new Error(`cannot sync debugging labs: ${incident.id} requires no evidence — reasoning goes unchecked`);
    }
    const fixes = incident.candidateFixes.map((f) => {
      if (typeof f?.id !== "string" || f.id.length === 0) {
        throw new Error(`cannot sync debugging labs: ${incident.id} has a candidate fix with no id`);
      }
      if (typeof f.addresses !== "string" || f.addresses.trim().length === 0) {
        throw new Error(`cannot sync debugging labs: ${incident.id} fix ${f.id} names no cause — the platform could not judge it`);
      }
      return {
        id: f.id,
        addresses: f.addresses,
        ...(f.regression === true ? { regression: true } : {}),
      };
    });
    const ids = fixes.map((f) => f.id);
    if (new Set(ids).size !== ids.length) {
      throw new Error(`cannot sync debugging labs: ${incident.id} has duplicate candidate fix ids`);
    }
    // The authoring gate guarantees exactly one fix addresses the cause without a
    // regression. The platform refuses to judge a lab that does not hold that
    // shape, because a lab with two "right" answers cannot be judged.
    const resolving = fixes.filter((f) => f.addresses === incident.rootCause && !f.regression);
    if (resolving.length !== 1) {
      throw new Error(
        `cannot sync debugging labs: ${incident.id} has ${resolving.length} fixes that address the cause without a regression; exactly one is required`
      );
    }
    return {
      id: incident.id,
      version,
      rootCause: incident.rootCause,
      candidateFixes: fixes,
      requiredEvidence: incident.requiredEvidence.slice(),
    };
  });

if (entries.length === 0) {
  throw new Error("cannot sync debugging labs: the IDE document holds no modelled lab to judge");
}

const emitted =
  `// Generated by npm run sync:incidents — do not edit by hand.\n` +
  `// Source: nexora-ide/extensions/nexora/curriculum/incidents.json\n` +
  `// The key only: id, authored revision, the cause the lab is built around, and\n` +
  `// the cause each candidate addresses. No symptom, no log, no failing tests,\n` +
  `// no evidence, no hints, no fix prose — the platform holds what it judges and\n` +
  `// nothing it could teach.\n` +
  `export interface SyncedIncident {\n` +
  `  id: string;\n` +
  `  version: number;\n` +
  `  rootCause: string;\n` +
  `  candidateFixes: { id: string; addresses: string; regression?: boolean }[];\n` +
  `  requiredEvidence: string[];\n` +
  `}\n` +
  `export const SYNCED_INCIDENTS: SyncedIncident[] = ${JSON.stringify(entries)};\n`;

if (check) {
  let prev = null;
  try {
    prev = await readFile(outFile, "utf8");
  } catch {
    prev = null;
  }
  if (prev !== emitted) {
    throw new Error(
      "debugging-lab sync has drifted: the committed registry no longer equals what the IDE source emits — " +
        "run `npm run sync:incidents` and commit the regenerated module. The platform must never judge a stale key."
    );
  }
  console.log(`debugging-lab sync clean (${entries.length} labs).`);
} else {
  await mkdir(dirname(outFile), { recursive: true });
  await writeFile(outFile, emitted, "utf8");
  console.log(`debugging labs synced (${entries.map((e) => `${e.id} v${e.version}`).join(", ")}).`);
}
